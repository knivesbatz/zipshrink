#!/usr/bin/env python3
"""Writes THIRD_PARTY_LICENSES.md from `cargo metadata` for the shipped
targets, and fails if any dependency has a license outside the allow list."""
import json, subprocess, sys
from collections import defaultdict
from pathlib import Path

ALLOWED = {"MIT", "Apache-2.0", "BSD-2-Clause", "BSD-3-Clause", "ISC", "Zlib", "Unicode-3.0", "Unicode-DFS-2016",
           "BSL-1.0", "CC0-1.0", "MPL-2.0", "OFL-1.1", "Apache-2.0 WITH LLVM-exception", "0BSD", "Unlicense", "CDLA-Permissive-2.0", "MIT-0", "bzip2-1.0.6"}
root = Path(__file__).resolve().parent.parent
crates = {}
for target in ["x86_64-pc-windows-gnu", "x86_64-unknown-linux-gnu", "aarch64-apple-darwin"]:
    meta = json.loads(subprocess.check_output(["cargo", "metadata", "--format-version", "1", "--filter-platform", target, "--manifest-path", str(root / "Cargo.toml")]))
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    pkgs = {p["id"]: p for p in meta["packages"]}
    # Only normal (non-dev, non-build) dependencies of the shipped binaries.
    stack = [p["id"] for p in meta["packages"] if p["name"] in ("zipshrink-cli", "zipshrink-gui")]
    seen = set()
    while stack:
        i = stack.pop()
        if i in seen:
            continue
        seen.add(i)
        for d in nodes[i]["deps"]:
            if any(k["kind"] in (None, "normal") for k in d["dep_kinds"]):
                stack.append(d["pkg"])
    for i in seen:
        p = pkgs[i]
        if p["name"].startswith("zipshrink"):
            continue
        crates[(p["name"], p["version"])] = (p.get("license") or "UNKNOWN", p.get("repository") or "")
bad = []
for (n, v), (lic, _) in crates.items():
    parts = [x.strip("() ") for x in lic.replace("/", " OR ").split(" OR ")]
    if not any(all(a.strip("() ") in ALLOWED for a in part.split(" AND ")) for part in parts):
        bad.append(f"{n} {v}: {lic}")
by = defaultdict(list)
for (n, v), (lic, repo) in sorted(crates.items()):
    by[lic].append((n, v, repo))
out = ["# Third-party licenses", "",
       "ZipShrink is MIT licensed. It is built from the Rust crates below, each under the license shown",
       "(where a crate offers a choice, ZipShrink uses it under any one of them). Generated by",
       "`scripts/third_party.py` from `cargo metadata`; every license is permissive and compatible with MIT.", "",
       "## Bundled assets", "",
       "* `assets/fonts/ZipShrinkPixel-*.ttf`: bitmap font derived from Liberation Sans, (c) 2012 Red Hat, Inc.,",
       "  SIL Open Font License 1.1 (see `assets/fonts/OFL.txt`). Renamed as the license requires.",
       "* egui's built-in fallback fonts (Ubuntu-Light: Ubuntu Font Licence 1.0; Hack: MIT/Bitstream Vera;",
       "  Noto Emoji: SIL OFL 1.1; emoji-icon-font: MIT/OFL), embedded by the `epaint_default_fonts` crate.", "",
       f"## Crates ({len(crates)})", ""]
for lic in sorted(by):
    out.append(f"### {lic}")
    out.append("")
    for n, v, repo in by[lic]:
        out.append(f"* {n} {v}" + (f" — {repo}" if repo else ""))
    out.append("")
(root / "THIRD_PARTY_LICENSES.md").write_text("\n".join(out))
print(f"{len(crates)} crates, {len(by)} license expressions")
if bad:
    print("Licenses needing review:\n  " + "\n  ".join(bad))
    sys.exit(1)
